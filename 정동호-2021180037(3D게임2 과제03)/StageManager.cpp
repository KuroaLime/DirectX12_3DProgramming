bool CStageManager::OnProcessingMouseMessage(HWND hWnd, UINT nMessageID, WPARAM wParam, LPARAM lParam, CCamera* pCamera) {
	bool handled = false;

	if (m_pScene)
	{
		handled = m_pScene->OnProcessingMouseMessage(hWnd, nMessageID, wParam, lParam, pCamera);
	}
	if (handled && m_pScene && m_pScene->GetSceneState())
	{
		m_bChangeSceneBool = m_pScene->GetSceneState();
		m_sceneHistory.push(m_bChangeSceneNum);
		m_bChangeSceneNum = m_pScene->GetSceneNum();
	}
	switch (nMessageID)
	{
	default:

		m_pScene->OnProcessingMouseMessage(hWnd, nMessageID, wParam, lParam, pCamera);
		break;
	}
	return(false);
}
bool CStageManager::OnProcessingKeyboardMessage(HWND hWnd, UINT nMessageID, WPARAM wParam, LPARAM lParam) {
	switch (nMessageID)
	{
	case WM_KEYUP:
		switch (wParam)
		{
		case VK_ESCAPE:
			if(m_bChangeSceneNum == MainMenuStage)
				::PostQuitMessage(0);
			else if (!m_sceneHistory.empty()) {
				m_bPopSceneApprove = true;
				m_bChangeSceneBool = m_bPopSceneApprove;
			}
			break;
		case VK_RETURN:
			OutputDebugStringA("StageManager: Enter key released!\n");
			if (m_pScene->GetSceneState()) {
				m_bChangeSceneBool = GetSceneState();
				m_sceneHistory.push(m_bChangeSceneNum);
				m_bChangeSceneNum = GetSceneNum();
			}
			break;
		default:
			m_pScene->OnProcessingKeyboardMessage(hWnd, nMessageID, wParam, lParam);
			break;
		}
		break;
	case WM_KEYDOWN:
		if (m_pScene) m_pScene->OnProcessingKeyboardMessage(hWnd, nMessageID, wParam, lParam);
		break;
	default:
		break;
	}
	return(false);

}

void CStageManager::BuildObjects(ID3D12Device* pd3dDevice, ID3D12GraphicsCommandList* pd3dCommandList) {
	if (!m_pd3dGraphicsRootSignature)
	{
		m_pd3dGraphicsRootSignature = CreateRepresentativeGraphicsRootSignature(pd3dDevice);
		m_pScene->m_pd3dGraphicsRootSignature = m_pd3dGraphicsRootSignature;
	}
	if (m_pScene)
	{

		m_pScene->BuildObjects(pd3dDevice, pd3dCommandList);
	}
}
void CStageManager::AnimateObjects(float fTimeElapsed) {

	if (m_pScene)
	{
		m_pScene->AnimateObjects(fTimeElapsed);
	}
}
bool CStageManager::GetNextSceneBool()
{

	return false;
}
