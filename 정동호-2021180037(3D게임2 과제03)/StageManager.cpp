CStageManager::CStageManager() {

	m_pScene = new CMainMenuScene();
	m_bChangeSceneNum = MainMenuStage;
}
CStageManager::~CStageManager() {
	if (m_pd3dGraphicsRootSignature) m_pd3dGraphicsRootSignature->Release();
	if (m_pScene)
	{
		m_pScene->ReleaseObjects();
		delete m_pScene;
		m_pScene = NULL;
	}
}
